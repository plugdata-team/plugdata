# Global whole-word find/replace, applied to the finished header. Use it for definitions we
# don't have: types that are private to the file we copy from map to void, since we only ever
# hold a pointer to them, and types we generate ourselves map to their t_fake_ name
REPLACE = {
    "t_fielddesc": "t_fake_fielddesc",
    "t_textbuf": "t_fake_textbuf",
    "t_canvas_mouse_proxy": "void",
    "t_canvas_vis_proxy": "void",
    "t_edit_proxy": "void",
    "t_messbox_proxy": "void",
    "t_zoom_proxy": "void",
    "t_copy": "void",
    "t_in": "void",
    "t_out": "void",
    "t_pdsample": "t_sample",
}

# Written above the structs. The array sizes here are the one thing not copied from the
# sources, so they have to be kept in sync by hand
PREAMBLE = """/*
 // Copyright (c) {year} Timothy Schoen
 // For information on usage and redistribution, and for a DISCLAIMER OF ALL
 // WARRANTIES, see the file, "LICENSE.txt," in this distribution.
 */

// This file is generated by Resources/Scripts/generate_all_guis.py, do not edit it by hand.
// It holds copies of struct definitions that are private to the pd, ELSE and cyclone sources,
// so that plugdata can read their fields. Re-run cmake after updating one of those libraries,
// and add new structs to the STRUCTS list in the script.

#pragma once
#include <g_canvas.h>

#define MAX_NUMBOX_LEN 32    // else/knob, else/numbox~
#define SCOPE_MAXBUFSIZE 256 // else/scope~

// clang-format off
"""


def extract_struct(text, tag, source):
    # Finds "struct <tag> {" and returns the braces and everything between them
    match = re.search(r"\bstruct\s+" + re.escape(tag) + r"\s*\{", text)
    if not match:
        raise LookupError("could not find 'struct %s' in %s" % (tag, source))

    start = text.index("{", match.start())
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start:index + 1]
    raise LookupError("unterminated 'struct %s' in %s" % (tag, source))


def generate(root):
    output = [PREAMBLE.format(year=datetime.date.today().year)]

    for name, source, tag, comment in STRUCTS:
        path = os.path.join(root, "Libraries", source)
        if not os.path.exists(path):
            raise LookupError("missing %s, did you check out the submodules?" % source)
        with open(path, "r", encoding="utf-8", errors="replace") as file:
            body = extract_struct(file.read(), tag, source)

        output.append("// %s (%s)\nstruct %s %s;\n" % (comment, source, name, body))

    output.append("// clang-format on\n")

    # \w+ only ever matches a whole identifier, so this can't rewrite part of a longer name
    return re.sub(r"\w+", lambda m: REPLACE.get(m.group(0), m.group(0)), "\n".join(output))


def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: generate_all_guis.py <output path for AllGuis.h>\n")
        return 1

    root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    destination = os.path.abspath(sys.argv[1])

    try:
        content = generate(root)
    except LookupError as error:
        sys.stderr.write("generate_all_guis.py: %s\n" % error)
        return 1

    os.makedirs(os.path.dirname(destination), exist_ok=True)

    if os.path.exists(destination):
        with open(destination, "r", encoding="utf-8") as file:
            if file.read() == content:
                return 0

    with open(destination, "w", encoding="utf-8", newline="\n") as file:
        file.write(content)
    print("Regenerated %s" % destination)
    return 0


if __name__ == "__main__":
    sys.exit(main())
