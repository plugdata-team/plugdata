#!/usr/bin/env python3

# Generates AllGuis.h into the build folder, its path is passed in as the first argument
#
# plugdata needs to read fields from objects whose struct definitions live inside a .c file
# of pd, ELSE or cyclone, and are therefore not visible to us. We used to keep hand-written
# copies of those structs, which silently went out of sync whenever one of the libraries was
# updated. This copies them straight out of the library sources instead, so re-running cmake
# is all it takes after updating a submodule.
#
# The struct body is copied verbatim, so any preprocessor conditionals in it are resolved by
# whoever includes AllGuis.h. Types that are private to the source file are substituted using
# the REPLACE table below; if you add a struct that references a new one, add it there too.

